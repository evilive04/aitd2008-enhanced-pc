"""Compile our D3D9 shader with the installed Windows SDK; no downloads/game data."""
from pathlib import Path
import argparse
import hashlib
import os
import struct
import subprocess

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--compiler', type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = root / 'src/performance/menu_nv12.hlsl'
header = root / 'src/performance/menu_nv12_shader.h'
digest = hashlib.sha256(source.read_bytes().replace(b'\r\n', b'\n')).hexdigest()
if args.check:
    if f'// Source SHA256 {digest}\n' not in header.read_text():
        raise SystemExit('Shader source changed; rebuild our generated bytecode')
    print('PASS own shader source hash matches generated header')
    raise SystemExit(0)
compiler = args.compiler
if compiler is None:
    sdk = Path(os.environ.get('ProgramFiles(x86)', r'C:/Program Files (x86)')) / 'Windows Kits/10/bin'
    candidates = sorted(sdk.glob('*/x86/fxc.exe'), key=lambda p: tuple(int(n) for n in p.parts[-3].split('.')))
    if not candidates:
        raise SystemExit('Installed Windows SDK fxc not found; pass --compiler')
    compiler = candidates[-1]
output = root / 'build/menu-shader/menu-nv12.cso'
output.parent.mkdir(parents=True, exist_ok=True)
subprocess.run([str(compiler), '/nologo', '/T', 'ps_2_0', '/E', 'main', '/O3', '/Fo', str(output), str(source)], check=True)
data = output.read_bytes()
if len(data) % 4:
    raise SystemExit('Invalid compiler output size')
words = struct.unpack(f'<{len(data)//4}I', data)
header.write_text('// Generated from our menu_nv12.hlsl by Windows SDK fxc ps_2_0/O3.\n'
                  f'// Source SHA256 {digest}\n#pragma once\nstatic const DWORD menuNv12Shader[]={{\n' +
                  ''.join('    ' + ','.join(f'0x{w:08x}u' for w in words[i:i+8]) + ',\n'
                          for i in range(0, len(words), 8)) + '};\n')
print(f'Built {len(data)} bytes of our shader bytecode')
